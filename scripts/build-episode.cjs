const fs=require('fs'),path=require('path'),vm=require('vm');
const root=path.resolve(__dirname,'../episode-1');
const original=path.join(root,'index.html');
const snapshot=path.join(root,'source/base.html');
if(!fs.existsSync(snapshot)) fs.copyFileSync(original,snapshot);
let html=fs.readFileSync(snapshot,'utf8');
const art=Array.from({length:8},(_,i)=>'data:image/jpeg;base64,'+fs.readFileSync(path.join(root,'art',`scene-${i+1}.jpg`)).toString('base64'));
html=html.replace(/background-image:url\('data:image\/jpeg;base64,[^']*'\);/g,'background-image:none;');
html=html.replace(/const openingArt=[\s\S]*?;\nconst scenes=/,'const storyArt='+JSON.stringify(art)+';\nconst scenes=');
const start=html.indexOf('function crop(node,i){'),end=html.indexOf('function stop(){',start);
if(start<0||end<0)throw Error('Expected artwork binding not found');
html=html.slice(0,start)+"function crop(node,i){node.style.backgroundImage='url('+storyArt[i]+')';node.style.backgroundSize='contain';node.style.backgroundPosition='center';node.style.aspectRatio='3 / 2'}"+html.slice(end);
html=html.replace('용과 기사 · 이야기와 단어 모험','용과 기사 · 안개빛 이야기');
html=html.replace('EPISODE 01 · STORY & WORD QUEST','EPISODE 01 · 안개빛 이야기');
html=html.replace('조금 마른 남성 기사, 사각 목제 방패, 옅게 채색한 중세풍 캐릭터와 청색·황토색 배경 대비를 적용했습니다.','2026년 10월 29일 고른 그림을 기준으로, 옅은 수채·과슈의 색과 안개 낀 계곡을 여덟 장면에 적용했습니다. 조금 마른 남성 기사, 사각 나무 방패와 용의 비늘·날개 질감을 유지했습니다.');
html=html.replace('</style>','.thumb .art{aspect-ratio:3/2!important;background-size:contain!important}.art{background-color:#ebe6da}.quest-art{margin-top:14px}html{scroll-behavior:smooth}@media(prefers-reduced-motion:reduce){html{scroll-behavior:auto}}</style>');
const scripts=[...html.matchAll(/<script>([\s\S]*?)<\/script>/g)];
scripts.forEach(s=>new vm.Script(s[1]));
if(!html.includes('const storyArt=')||art.length!==8)throw Error('Missing scene art');
const target=path.join(root,'index.html');
fs.writeFileSync(target,html);
console.log(JSON.stringify({file:target,bytes:Buffer.byteLength(html),sceneImages:art.length,embeddedAudio:(html.match(/data:audio\/mpeg;base64,/g)||[]).length,inlineScriptsValid:true}));
